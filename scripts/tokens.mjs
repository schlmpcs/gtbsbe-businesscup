#!/usr/bin/env node
// tokens.json (Figma variables export, DTCG-style `$type` / `$value`) → apps/web/src/ui-kit/tokens.css
//
// The output is a Tailwind v4 `@theme static` block, so every token is both a CSS variable
// (`var(--color-primary)`) and a Tailwind utility (`bg-primary`, `rounded-md`, `shadow-md`, `p-lg`).
// The default Tailwind color palette is cleared, so only token colors exist.
//
// Usage: node scripts/tokens.mjs           write tokens.css
//        node scripts/tokens.mjs --check   exit 1 if tokens.css is out of date (run in `pnpm lint`)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = resolve(root, 'tokens.json');
const outputPath = resolve(root, 'apps/web/src/ui-kit/tokens.css');

/** tokens.json top-level group → Tailwind v4 theme namespace (CSS variable prefix). */
const NAMESPACES = {
  color: 'color',
  font: 'font',
  text: 'text',
  leading: 'leading',
  fontWeight: 'font-weight',
  spacing: 'spacing',
  radius: 'radius',
  shadow: 'shadow',
};

const fail = (message) => {
  console.error(`tokens: ${message}`);
  process.exit(1);
};

const isToken = (node) => node !== null && typeof node === 'object' && '$value' in node;

/** Collect leaf tokens as { path: ['color', 'chart', '1'], token }. */
function collect(node, path, out) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (!/^[a-zA-Z0-9-]+$/.test(key)) fail(`invalid token name "${[...path, key].join('.')}" (use letters, digits, -)`);
    if (isToken(child)) out.push({ path: [...path, key], token: child });
    else if (child && typeof child === 'object') collect(child, [...path, key], out);
    else fail(`"${[...path, key].join('.')}" is neither a token nor a group`);
  }
  return out;
}

const varName = (path) => {
  const [group, ...rest] = path;
  const ns = NAMESPACES[group];
  if (!ns) fail(`unknown top-level group "${group}". Known: ${Object.keys(NAMESPACES).join(', ')}`);
  return `--${ns}-${rest.join('-')}`;
};

function formatValue({ path, token }) {
  const { $type: type, $value: value } = token;
  if (typeof value === 'string') {
    // DTCG alias: "{color.primary}" → var(--color-primary)
    const alias = value.match(/^\{([^}]+)\}$/);
    return alias ? `var(${varName(alias[1].split('.'))})` : value;
  }
  if (typeof value === 'number') return type === 'dimension' ? `${value}px` : String(value);
  if (Array.isArray(value) && type === 'fontFamily') {
    return value.map((f) => (/^[a-z-]+$/i.test(f) && !/\s/.test(f) ? f : `"${f}"`)).join(', ');
  }
  return fail(`unsupported value for "${path.join('.')}": ${JSON.stringify(value)}`);
}

if (!existsSync(inputPath)) fail(`missing ${inputPath}`);
const tokens = collect(JSON.parse(readFileSync(inputPath, 'utf8')), [], []);
const seen = new Set();
const lines = tokens.map((t) => {
  const name = varName(t.path);
  if (seen.has(name)) fail(`duplicate variable ${name}`);
  seen.add(name);
  return `  ${name}: ${formatValue(t)};`;
});

const css = `/* Generated by \`pnpm tokens\` from tokens.json. Do not edit by hand. */
@theme static {
  --color-*: initial;
${lines.join('\n')}
}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== css) fail('apps/web/src/ui-kit/tokens.css is out of date with tokens.json. Run `pnpm tokens`.');
  console.log('tokens: tokens.css is up to date');
} else {
  writeFileSync(outputPath, css);
  console.log(`tokens: wrote ${tokens.length} tokens to apps/web/src/ui-kit/tokens.css`);
}
